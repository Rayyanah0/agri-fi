/* eslint-disable no-console */
/**
 * Safe migration CLI.
 *
 *   ts-node src/database/migration-tooling/migrate.ts <command> [options]
 *
 * Commands:
 *   status            Show executed / pending migrations with versions
 *   lint              Static safety checks on migration files
 *   up                Backup → run pending → validate → record → document
 *   down [--steps N]  Roll back the last N migrations (default 1)
 *   test              Staging dry-run: up → down → up for every pending migration
 *   restore <file>    Restore a pre-migration backup
 *   history           Print migration run history
 *   analytics         Print duration / success-rate analytics
 *
 * Options:
 *   --no-backup       Skip pg_dump (NOT allowed when NODE_ENV=production)
 *   --dry-run         Print what would run without executing
 */
import { appendFileSync, existsSync, mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import { execSync } from 'child_process';
import { DataSource } from 'typeorm';
import dataSource from '../data-source';
import {
  backupDatabase,
  ConnectionInfo,
  diffSchemas,
  lintMigrations,
  restoreDatabase,
  snapshotSchema,
  validateSchema,
} from './migration-safety';
import { extractVersion, MigrationTracker } from './migration-tracker';

const MIGRATIONS_DIR = join(__dirname, '..', 'migrations');
const BACKUP_DIR = process.env.MIGRATION_BACKUP_DIR || join(process.cwd(), 'backups', 'migrations');
const CHANGELOG = process.env.MIGRATION_CHANGELOG || join(process.cwd(), '..', 'docs', 'database', 'schema-changelog.md');
const ENV = process.env.NODE_ENV || 'development';

const args = process.argv.slice(2);
const cmd = args[0] || 'status';
const flag = (n: string) => args.includes(`--${n}`);
const opt = (n: string, d: string) => {
  const i = args.indexOf(`--${n}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : d;
};

function conn(ds: DataSource): ConnectionInfo {
  const o: any = ds.options;
  return {
    host: o.host ?? 'localhost',
    port: Number(o.port ?? 5432),
    username: o.username,
    password: o.password,
    database: o.database,
  };
}

function gitSha(): string | null {
  try {
    return process.env.GITHUB_SHA || execSync('git rev-parse HEAD').toString().trim();
  } catch {
    return null;
  }
}

function executor(): string {
  return process.env.GITHUB_ACTOR || process.env.USER || 'unknown';
}

async function pendingNames(ds: DataSource): Promise<string[]> {
  const executed = new Set(
    (await ds.query(`SELECT name FROM migrations`).catch(() => [])).map((r: any) => r.name),
  );
  return ds.migrations.map((m) => m.name || m.constructor.name).filter((n) => !executed.has(n));
}

function doBackup(ds: DataSource): string | null {
  if (flag('no-backup')) {
    if (ENV === 'production') throw new Error('--no-backup is forbidden in production');
    return null;
  }
  const file = backupDatabase(conn(ds), BACKUP_DIR);
  console.log(`✔ Backup written: ${file}`);
  return file;
}

function document(names: string[], diff: string) {
  const dir = join(CHANGELOG, '..');
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  if (!existsSync(CHANGELOG)) writeFileSync(CHANGELOG, '# Schema Changelog\n\nAuto-generated by `migrate.ts up`.\n');
  appendFileSync(
    CHANGELOG,
    `\n## ${new Date().toISOString()} — ${ENV}\n\n` +
      `Migrations: ${names.map((n) => `\`${n}\` (v${extractVersion(n)})`).join(', ')}\n\n${diff}\n`,
  );
}

async function up(ds: DataSource, tracker: MigrationTracker) {
  const pending = await pendingNames(ds);
  if (!pending.length) return console.log('No pending migrations.');
  console.log(`Pending: ${pending.join(', ')}`);
  if (flag('dry-run')) return;

  const errors = lintMigrations(MIGRATIONS_DIR).filter((f) => f.level === 'error');
  if (errors.length) {
    errors.forEach((e) => console.error(`✖ ${e.file}: ${e.message}`));
    throw new Error('Migration lint failed');
  }

  const backupFile = doBackup(ds);
  const before = await snapshotSchema(ds);

  // Instrument each migration's up() so every migration is tracked individually.
  for (const m of ds.migrations) {
    const name = m.name || m.constructor.name;
    if (!pending.includes(name)) continue;
    const original = m.up.bind(m);
    m.up = async (qr) => {
      const id = await tracker.start({
        migrationName: name, version: extractVersion(name), direction: 'up', status: 'running',
        environment: ENV, backupFile, executedBy: executor(), gitSha: gitSha(),
      });
      const t0 = Date.now();
      try {
        await original(qr);
        await tracker.finish(id, 'success', Date.now() - t0);
        console.log(`✔ ${name} (${Date.now() - t0}ms)`);
      } catch (e: any) {
        await tracker.finish(id, 'failed', Date.now() - t0, e.message);
        console.error(`✖ ${name} failed: ${e.message}`);
        throw e;
      }
    };
  }
  try {
    await ds.runMigrations({ transaction: 'each' });
  } catch (e) {
    if (backupFile && flag('restore-on-fail')) restoreDatabase(conn(ds), backupFile);
    throw e;
  }

  const v = await validateSchema(ds);
  if (!v.ok) {
    console.error('✖ Validation failed', v);
    throw new Error('Post-migration validation failed');
  }
  console.log('✔ Post-migration validation passed');
  document(pending, diffSchemas(before, await snapshotSchema(ds)));
}

async function down(ds: DataSource, tracker: MigrationTracker) {
  const steps = Number(opt('steps', '1'));
  const backupFile = doBackup(ds);
  for (let i = 0; i < steps; i++) {
    const [last] = await ds.query(`SELECT name FROM migrations ORDER BY id DESC LIMIT 1`);
    if (!last) break;
    if (flag('dry-run')) { console.log(`Would revert ${last.name}`); continue; }
    const id = await tracker.start({
      migrationName: last.name, version: extractVersion(last.name), direction: 'down', status: 'running',
      environment: ENV, backupFile, executedBy: executor(), gitSha: gitSha(),
    });
    const t0 = Date.now();
    try {
      await ds.undoLastMigration({ transaction: 'each' });
      await tracker.finish(id, 'success', Date.now() - t0);
      console.log(`✔ Reverted ${last.name}`);
    } catch (e: any) {
      await tracker.finish(id, 'failed', Date.now() - t0, e.message);
      throw e;
    }
  }
}

/** Staging test: verifies each pending migration is reversible (up → down → up). */
async function test(ds: DataSource, tracker: MigrationTracker) {
  if (ENV === 'production') throw new Error('migration test must not run against production');
  const pending = await pendingNames(ds);
  for (const name of pending) {
    const id = await tracker.start({
      migrationName: name, version: extractVersion(name), direction: 'test', status: 'running',
      environment: ENV, executedBy: executor(), gitSha: gitSha(),
    });
    const t0 = Date.now();
    try {
      const before = await snapshotSchema(ds);
      await ds.runMigrations({ transaction: 'each' });
      const ran = (await ds.query(`SELECT name FROM migrations ORDER BY id DESC LIMIT 1`))[0]?.name;
      await ds.undoLastMigration({ transaction: 'each' });
      const reverted = await snapshotSchema(ds);
      if (diffSchemas(before, reverted) !== '_No structural changes._') {
        throw new Error(`down() of ${ran} does not restore the original schema`);
      }
      await ds.runMigrations({ transaction: 'each' });
      await tracker.finish(id, 'success', Date.now() - t0);
      console.log(`✔ ${name} is reversible`);
    } catch (e: any) {
      await tracker.finish(id, 'failed', Date.now() - t0, e.message);
      throw e;
    }
  }
  const v = await validateSchema(ds);
  if (!v.ok) throw new Error(`Validation failed: ${JSON.stringify(v)}`);
}

async function main() {
  if (cmd === 'lint') {
    const f = lintMigrations(MIGRATIONS_DIR);
    f.forEach((x) => console.log(`${x.level === 'error' ? '✖' : '⚠'} ${x.file}: ${x.message}`));
    process.exit(f.some((x) => x.level === 'error') ? 1 : 0);
  }
  const ds = await dataSource.initialize();
  const tracker = new MigrationTracker(ds);
  await tracker.ensureTable();
  try {
    switch (cmd) {
      case 'status': {
        const executed = await ds.query(`SELECT name, timestamp FROM migrations ORDER BY id`);
        executed.forEach((r: any) => console.log(`[x] v${extractVersion(r.name)} ${r.name}`));
        (await pendingNames(ds)).forEach((n) => console.log(`[ ] v${extractVersion(n)} ${n}`));
        break;
      }
      case 'up': await up(ds, tracker); break;
      case 'down': await down(ds, tracker); break;
      case 'test': await test(ds, tracker); break;
      case 'restore': restoreDatabase(conn(ds), args[1]); break;
      case 'history': console.table(await tracker.history(Number(opt('limit', '50')))); break;
      case 'analytics': console.log(JSON.stringify(await tracker.analytics(), null, 2)); break;
      default: throw new Error(`Unknown command ${cmd}`);
    }
  } finally {
    await ds.destroy();
  }
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
